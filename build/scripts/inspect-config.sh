#!/bin/sh
# inspetor rapido do .config gerado (uso interno)
CFG=/root/winux/build/config/.config.generated
[ -f "$CFG" ] || { echo "sem .config.generated"; exit 1; }
for sym in \
    CONFIG_64BIT CONFIG_SMP CONFIG_PRINTK CONFIG_BLK_DEV_INITRD CONFIG_RD_GZIP \
    CONFIG_DEVTMPFS CONFIG_DEVTMPFS_MOUNT CONFIG_PROC_FS CONFIG_SYSFS \
    CONFIG_BINFMT_ELF CONFIG_MODULES CONFIG_EFI CONFIG_EFI_STUB CONFIG_ACPI \
    CONFIG_PCI CONFIG_HZ CONFIG_TMPFS CONFIG_TTY CONFIG_VT CONFIG_VT_CONSOLE \
    CONFIG_FRAMEBUFFER_CONSOLE CONFIG_DUMMY_CONSOLE CONFIG_SERIAL_8250 \
    CONFIG_SERIAL_8250_CONSOLE CONFIG_SERIAL_8250_PCI CONFIG_SERIAL_EARLYCON \
    CONFIG_SERIAL_CORE CONFIG_SERIAL_CORE_CONSOLE CONFIG_NET CONFIG_INET \
    CONFIG_SCSI CONFIG_BLK_DEV_SD CONFIG_ATA CONFIG_SATA_AHCI CONFIG_BLK_DEV_NVME \
    CONFIG_BTRFS_FS CONFIG_XFS_FS CONFIG_EXT4_FS CONFIG_SQUASHFS \
    CONFIG_BLK_DEV_LOOP CONFIG_FB CONFIG_FB_EFI CONFIG_DRM \
    CONFIG_CPU_FREQ CONFIG_CPU_FREQ_DEFAULT_GOV_PERFORMANCE CONFIG_PREEMPT \
    CONFIG_IO_URING CONFIG_NR_CPUS CONFIG_RTC_CLASS CONFIG_DEVPTS_FS \
    CONFIG_INPUT CONFIG_HID CONFIG_USB CONFIG_USB_XHCI_HCD CONFIG_SND \
    CONFIG_SND_HDA_INTEL CONFIG_MICROCODE CONFIG_CC_OPTIMIZE_FOR_PERFORMANCE \
    CONFIG_KERNEL_XZ CONFIG_OVERLAY_FS CONFIG_CGROUPS CONFIG_IPV6; do
    grep -qE "^$sym=y" "$CFG" && echo "ON  $sym" || { grep -qE "^# $sym is not set" "$CFG" && echo "OFF $sym" || echo "--  $sym (ausente)"; }
done